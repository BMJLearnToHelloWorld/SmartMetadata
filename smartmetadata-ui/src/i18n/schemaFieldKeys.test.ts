import { describe, expect, it } from 'vitest';
import {
  deref,
  getSchemaByWorkflowType,
  SERVICE_CATEGORY_BY_KIND,
  startCase,
  type RjsfSchema,
} from '@/ingestion/ingestionSchemas';
import {
  formDisplayLabel,
  schemaSlugFor,
  type MetadataSchemaSlug,
} from '@/ingestion/schemaFieldLabels';
import type { ServiceKind } from '@/types/ingestion';
import enUS from './locales/en-US';
import zhCN from './locales/zh-CN';

/**
 * Mechanical check of the `forms.schemaFields.*` key set: the expected
 * set is generated by walking the nine real metadata schemas under the
 * same rules the key design uses (property recursion, branch segments,
 * filter-fields-description-only, hidden top-level `type` excluded),
 * plus the fixed shared/option keys. The walker shares the design's
 * rules, so this test pins the catalog against the schemas, not against
 * an independent enumeration.
 */

const METADATA_KINDS: ServiceKind[] = [
  'database',
  'dashboard',
  'api',
  'messaging',
  'mlmodel',
  'pipeline',
  'storage',
  'search',
  'drive',
];

/** Fixed shared keys (§2.3): key → [en-US, zh-CN]. */
const SHARED_KEYS: Record<string, [string, string]> = {
  'forms.schemaFields.shared.enableDebugLog.label': ['Enable Debug Log', '启用调试日志'],
  'forms.schemaFields.branchTypes.string': ['String', '字符串'],
  'forms.schemaFields.branchTypes.object': ['Object', '对象'],
  'forms.schemaFields.branchTypes.integer': ['Integer', '整数'],
  'forms.schemaFields.branchTypes.number': ['Number', '数字'],
  'forms.schemaFields.branchTypes.boolean': ['Boolean', '布尔值'],
  'forms.schemaFields.branchTypes.array': ['Array', '数组'],
  'forms.schemaFields.branchOption': ['Option {n}', '选项 {n}'],
  'forms.schemaFields.invalidJson': ['Invalid JSON', 'JSON 格式无效'],
};

/** Fixed D6 enum option keys (§4.5): key → [en-US, zh-CN]. */
const OPTION_KEYS: Record<string, [string, string]> = {
  'forms.schemaFields.pipeline.ownershipUpdateMode.options.replace': ['replace', '替换'],
  'forms.schemaFields.pipeline.ownershipUpdateMode.options.append': ['append', '追加'],
};

/**
 * Keys whose zh-CN value is legitimately identical to the en-US value:
 * only when the en-US value contains nothing translatable (a bare
 * proper noun, identifier, or literal with no prose around it). A key
 * enters this list only with a recorded reason; forcing zh != en on
 * such a key would mandate a mistranslation (RECOUNT §6.7). Currently
 * empty: every key's zh value differs from its en value.
 */
const ZH_EQUALS_EN_WHITELIST: ReadonlySet<string> = new Set([]);

function isFilterPatternShape(schema: RjsfSchema): boolean {
  const keys = Object.keys(schema.properties ?? {});
  return keys.length === 2 && keys.includes('includes') && keys.includes('excludes');
}

interface ExpectedKey {
  key: string;
  enValue: string;
}

function walkMetadataSchema(root: RjsfSchema, slug: MetadataSchemaSlug): ExpectedKey[] {
  const out: ExpectedKey[] = [];
  const rootPrefix = `forms.schemaFields.${slug}`;

  function walkProperties(
    properties: Record<string, RjsfSchema>,
    prefix: string,
    topLevel: boolean,
  ): void {
    for (const [fieldName, fieldSchema] of Object.entries(properties)) {
      // Only the top-level computed `type` is hidden; nested fields
      // named `type` (queryParserConfig.type, gcpConfig branches) are
      // real fields with keys.
      if (topLevel && fieldName === 'type') {
        continue;
      }
      walkField(fieldName, fieldSchema, `${prefix}.${fieldName}`);
    }
  }

  function walkArrayItems(schema: RjsfSchema, prefix: string): void {
    // Object-array rows contribute no key segment: children hang off the
    // field prefix itself.
    const items = schema.items;
    if (items && typeof items === 'object' && !Array.isArray(items)) {
      const resolvedItems = deref(items, root);
      if (resolvedItems.properties) {
        walkProperties(resolvedItems.properties, prefix, false);
      }
    }
  }

  function walkField(fieldName: string, schema: RjsfSchema, prefix: string): void {
    const resolved = deref(schema, root);
    if (isFilterPatternShape(resolved)) {
      // Filter cards render via FilterPatternCard, not SchemaField: only
      // the description key exists, and the includes/excludes children
      // (already covered by forms.filter.*) get no keys.
      if (typeof resolved.description === 'string') {
        out.push({ key: `${prefix}.description`, enValue: resolved.description });
      }
      return;
    }
    out.push({ key: `${prefix}.label`, enValue: resolved.title ?? startCase(fieldName) });
    if (typeof resolved.description === 'string') {
      out.push({ key: `${prefix}.description`, enValue: resolved.description });
    }
    const branches = resolved.oneOf ?? resolved.anyOf;
    if (branches) {
      branches.forEach((branch, index) => {
        const resolvedBranch = deref(branch, root);
        if (resolvedBranch.title !== undefined) {
          out.push({
            key: `${prefix}.branches.b${index}.label`,
            enValue: formDisplayLabel(resolvedBranch.title),
          });
        }
        if (typeof resolvedBranch.description === 'string') {
          out.push({
            key: `${prefix}.branches.b${index}.description`,
            enValue: resolvedBranch.description,
          });
        }
        if (resolvedBranch.properties) {
          walkProperties(resolvedBranch.properties, `${prefix}.b${index}`, false);
        }
        walkArrayItems(resolvedBranch, `${prefix}.b${index}`);
      });
    }
    if (resolved.properties) {
      walkProperties(resolved.properties, prefix, false);
    }
    walkArrayItems(resolved, prefix);
  }

  walkProperties(root.properties ?? {}, rootPrefix, true);
  return out;
}

async function expectedKeys(): Promise<ExpectedKey[]> {
  const out: ExpectedKey[] = [];
  for (const kind of METADATA_KINDS) {
    const schema = await getSchemaByWorkflowType(
      'metadata',
      SERVICE_CATEGORY_BY_KIND[kind],
      kind === 'database' ? 'BigQuery' : undefined,
    );
    const slug = schemaSlugFor(schema);
    expect(slug).toBe(kind);
    out.push(...walkMetadataSchema(schema, slug!));
  }
  for (const [key, [enValue]] of Object.entries(SHARED_KEYS)) {
    out.push({ key, enValue });
  }
  for (const [key, [enValue]] of Object.entries(OPTION_KEYS)) {
    out.push({ key, enValue });
  }
  return out;
}

function leafKeys(value: unknown, prefix = ''): string[] {
  if (value !== null && typeof value === 'object') {
    return Object.entries(value as Record<string, unknown>).flatMap(([key, child]) =>
      leafKeys(child, prefix ? `${prefix}.${key}` : key),
    );
  }
  return prefix ? [prefix] : [];
}

function lookup(catalog: unknown, dottedKey: string): unknown {
  let current: unknown = catalog;
  for (const segment of dottedKey.split('.')) {
    if (current === null || typeof current !== 'object') {
      return undefined;
    }
    current = (current as Record<string, unknown>)[segment];
  }
  return current;
}

describe('i18n schemaFields keys', () => {
  it('contains exactly the designed schemaFields keys in both catalogs', async () => {
    const expected = (await expectedKeys()).map((entry) => entry.key).sort();
    expect(expected).toHaveLength(372);
    expect(new Set(expected).size).toBe(expected.length);
    const enKeys = leafKeys(enUS.forms.schemaFields).map((key) => `forms.schemaFields.${key}`).sort();
    const zhKeys = leafKeys(zhCN.forms.schemaFields).map((key) => `forms.schemaFields.${key}`).sort();
    expect(enKeys).toEqual(expected);
    expect(zhKeys).toEqual(expected);
  });

  it('keeps en-US field values byte-identical to schema sources', async () => {
    const expected = await expectedKeys();
    for (const { key, enValue } of expected) {
      expect(lookup(enUS, key)).toBe(enValue);
    }
  });

  it('keeps zh-CN values translated (zh != en unless whitelisted)', async () => {
    const expected = await expectedKeys();
    expect(expected).toHaveLength(372);
    const expectedKeySet = new Set(expected.map((entry) => entry.key));
    for (const key of ZH_EQUALS_EN_WHITELIST) {
      expect(expectedKeySet.has(key)).toBe(true);
    }
    for (const { key } of expected) {
      const enValue = lookup(enUS, key);
      const zhValue = lookup(zhCN, key);
      expect(typeof zhValue).toBe('string');
      expect(zhValue !== enValue || ZH_EQUALS_EN_WHITELIST.has(key)).toBe(true);
    }
    for (const [key, [, zhValue]] of Object.entries(SHARED_KEYS)) {
      expect(lookup(zhCN, key)).toBe(zhValue);
    }
    for (const [key, [, zhValue]] of Object.entries(OPTION_KEYS)) {
      expect(lookup(zhCN, key)).toBe(zhValue);
    }
  });

  it('keeps the advancedDescription Chinese value translated', () => {
    expect(zhCN.forms.sections.advancedDescription).toBe(
      '驱动级选项 — 连接参数、协议方案和超时时间。绝大多数连接都不需要这些设置。',
    );
    expect(enUS.forms.sections.advancedDescription).toBe(
      'Driver-level options — connection arguments, scheme, and timeouts. Most connections never need these.',
    );
  });

  it('keeps the markDeletedContainers description free of design annotations', () => {
    // Q-1 (Bai, option A): en copies the schema text verbatim (including
    // the suspect `topic` wording); zh translates by field intent. A
    // design annotation once leaked into the zh value (B-1); pin both
    // values exactly so no annotation text can hide in either.
    expect(zhCN.forms.schemaFields.storage.markDeletedContainers.description).toBe(
      '可选配置，用于在源存储容器被删除时，在 OpenMetadata 中软删除存储容器。此外，如果存储容器被删除，与该存储容器关联的所有实体也会被删除。',
    );
    expect(enUS.forms.schemaFields.storage.markDeletedContainers.description).toBe(
      'Optional configuration to soft delete containers in OpenMetadata if the source containers are deleted. Also, if the topic is deleted, all the associated entities with that containers will be deleted',
    );
  });

  it('keeps the two shared doc-panel fallback descriptions translated', () => {
    expect(zhCN.forms.docPanel.docsDescription).toBe(
      '完整的设置指南、所需权限和每个支持的字段。',
    );
    expect(zhCN.forms.docPanel.focusedFallbackDescription).toBe(
      '在测试连接之前，请查看要求和聚焦字段的指导。',
    );
    expect(enUS.forms.docPanel.docsDescription).toBe(
      'Full setup guide, required privileges, and every supported field.',
    );
    expect(enUS.forms.docPanel.focusedFallbackDescription).toBe(
      'Review the requirements and focused field guidance before testing the connection.',
    );
  });
});
